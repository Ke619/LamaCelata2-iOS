#!/usr/bin/env python3
# stub_undefined.py NM OUT.cpp LIB.a [DEFINING_LIB.a...]: a C++ file defining,
# as functions that stop the run, every scimitar::overrides function LIB.a
# calls that no DEFINING_LIB.a defines. For ac2-loadtest, which links the
# translated game without the shell and game code that implement them.
import subprocess, sys

nm, out, lib, *others = sys.argv[1:]
def syms(path, flag):
    r = subprocess.run([nm, flag, path], capture_output=True, text=True, check=True).stdout
    return {l.split()[-1] for l in r.splitlines() if l.strip() and not l.endswith(':')}
undefined = syms(lib, '-u') - syms(lib, '--defined-only')
for o in others:
    undefined -= syms(o, '--defined-only')
prefix = '_ZN8scimitar9overrides'
names = []
for s in sorted(undefined):
    if not s.startswith(prefix) or not s.endswith('ERNS_7ContextE'):
        continue
    rest = s[len(prefix):]
    n = 0
    while rest[n].isdigit():
        n += 1
    names.append(rest[n:n + int(rest[:n])])
with open(out, 'w') as f:
    f.write('// Generated by platform/vita/stub_undefined.py. Do not edit.\n'
            '#include "scimitar/runtime.h"\n\nnamespace scimitar::overrides {\n')
    for n in names:
        f.write(f'void {n}(scimitar::Context&) {{ scimitar::fatal("{n} is not in the load test"); }}\n')
    f.write('}  // namespace scimitar::overrides\n')
print(f'{len(names)} override stubs')
