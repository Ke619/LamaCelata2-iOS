#!/bin/bash
# Writes platform/src/metal/gl_enums.h: the GL enumerants the Metal backend
# uses, with their values from the macOS SDK's OpenGL headers, so the backend
# builds without desktop GL headers (iOS). Run after the backend uses a new one.
set -euo pipefail
cd "$(dirname "$0")/.."
SDK="$(xcrun --sdk macosx --show-sdk-path)/System/Library/Frameworks/OpenGL.framework/Headers"
OUT=platform/src/metal/gl_enums.h
names=$(grep -ohE '\bGL_[A-Z0-9_]+\b' platform/src/metal/*.mm platform/src/metal/*.h | sort -u |
        grep -vxE 'GL_SILENCE_DEPRECATION|GL_ENUMS_H')
{
cat <<'EOF'
// The OpenGL enumerants the Metal backend uses, with the values the macOS
// SDK's gl.h and glext.h give them (the Khronos registry's), so the backend
// builds where there are no desktop GL headers (iOS). Generated by
// tools/gen_gl_enums.sh; run it again after using a new one.
#pragma once
#include <cstdint>

typedef uint32_t GLenum;
typedef uint32_t GLuint;
typedef int32_t GLint;
typedef int32_t GLsizei;
typedef uint32_t GLbitfield;
typedef uint8_t GLboolean;
typedef float GLfloat;
typedef double GLdouble;

EOF
for n in $names; do
    v=$(grep -hE "^#define[[:space:]]+$n[[:space:]]" "$SDK/gl.h" "$SDK/glext.h" | head -1 | awk '{print $3}')
    if [ -z "$v" ]; then echo "gen_gl_enums: no value for $n" >&2; exit 1; fi
    printf '#define %-44s %s\n' "$n" "$v"
done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(grep -c '^#define GL_' "$OUT") enumerants)"
