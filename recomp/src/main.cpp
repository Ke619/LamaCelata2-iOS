// scimitar-recomp: translates i386 code into C++.
//
// Fixture mode (one self-contained function from raw bytes):
//   scimitar-recomp --bin CODE.bin --addr 0xADDR --name NAME --out OUT.cpp
//
// Image mode (functions from the game executable and everything they call):
//   scimitar-recomp --image BINARY --root SYMBOL... [--roots-file FILE] [--override SYMBOL]...
//                   [--no-vtables] [--weak-imports] [--parts N] --out OUT.cpp
//   scimitar-recomp --image BINARY --all [--parts N] --out OUT.cpp   (the whole image)
//
// Roots are symbols or 0xADDR; a roots file holds one per line ('#' comments).
// Image mode follows direct calls and tail calls from the roots and translates
// every function reached, except overrides: those forward to hand-written code
// named after their symbol (scimitar::overrides::ov_SYMBOL, see override_symbol), and, unless --no-vtables, every function in a vtable
// the translated code refers to and every function whose address it takes. With --parts N the output is split into
// OUT_0.cpp .. OUT_{N-1}.cpp of about equal size. --weak-imports adds a weak
// stub for every import that calls fatal(); a real shim linked in replaces it
// (link the platform library with -force_load so the linker sees its shims). Calls to external imports become calls to
// scimitar::imports::imp_* shims. The output registers every translated
// function for indirect calls. It contains translated game code: build output
// only, never commit it.

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>
#include <set>
#include <string>
#include <vector>

#include "emit.h"
#include "flow.h"
#include "macho.h"

using namespace recomp;

[[noreturn]] static void usage() {
    std::fprintf(stderr,
                 "usage: scimitar-recomp --bin CODE.bin --addr 0xADDR --name NAME --out OUT.cpp\n"
                 "       scimitar-recomp --image BINARY --root SYMBOL... [--roots-file FILE] "
                 "[--override SYMBOL]... [--no-vtables] --out OUT.cpp\n");
    std::exit(2);
}

static int fixture_mode(const std::string& bin, uint32_t base, const std::string& name,
                        const std::string& out_path) {
    std::ifstream f(bin, std::ios::binary);
    std::vector<uint8_t> code{std::istreambuf_iterator<char>(f), {}};
    if (code.empty()) {
        std::fprintf(stderr, "cannot read %s\n", bin.c_str());
        return 1;
    }
    DecodedFunction fn = decode_function(code.data(), base, base + (uint32_t)code.size(), nullptr);
    EmitResult r;
    try {
        r = emit_function(fn, name, nullptr, "");
    } catch (const EmitError& e) {
        std::fprintf(stderr, "scimitar-recomp: %s: %s\n", name.c_str(), e.what());
        return 1;
    }
    std::ofstream(out_path)
        << "// Generated by scimitar-recomp from " << bin << ". Do not edit.\n"
        << "#include \"scimitar/runtime.h\"\n\nnamespace generated {\n\n"
        << r.code << "\n}  // namespace generated\n";
    std::fprintf(stderr, "%s: %zu instructions, flag writes %d of %d kept by liveness\n",
                 name.c_str(), fn.insns.size(), r.flag_writes_kept, r.flag_writes);
    return 0;
}

static int image_mode(const std::string& path, std::vector<std::string> roots,
                      const std::vector<std::string>& overrides, bool follow_vtables,
                      bool weak_imports, size_t parts, const std::string& out_path) {
    Image image(path);
    discover_functions(image);  // code without symbols that direct calls reach
    const bool all = roots.size() == 1 && roots[0] == "--all";
    if (all) {  // every function of the image; any that fail become stubs
        roots.clear();
        for (const Function& f : image.functions()) {
            char buf[16];
            std::snprintf(buf, sizeof buf, "0x%08x", f.addr);
            roots.push_back(buf);
        }
    }
    auto resolve = [&](const std::string& sym) {
        const Function* f = sym.rfind("0x", 0) == 0
                                ? image.function_at((uint32_t)std::stoul(sym, nullptr, 16))
                                : image.function_named(sym);
        if (!f) {
            std::fprintf(stderr, "no function named %s\n", sym.c_str());
            std::exit(1);
        }
        return f->addr;
    };
    std::set<uint32_t> overridden;
    for (const auto& s : overrides) overridden.insert(resolve(s));

    std::map<uint32_t, std::string> bodies;
    std::set<std::string> imports;
    std::vector<uint32_t> work;
    for (const auto& s : roots) work.push_back(resolve(s));
    // Functions reached by direct calls must translate; ones reached only
    // through vtables may become stubs that fail if they are ever called.
    const std::vector<uint32_t> root_addrs = work;
    std::map<uint32_t, std::string> stubbed;
    std::map<uint32_t, std::set<uint32_t>> callees_of;
    size_t insns = 0;
    int indirect_calls = 0;
    std::set<uint32_t> via_vtables;
    while (!work.empty()) {
        const uint32_t a = work.back();
        work.pop_back();
        if (bodies.count(a) || overridden.count(a)) continue;
        const Function* f = image.function_at(a);
        DecodedFunction fn =
            decode_image_function(image, *f);
        for (const auto& [ia, i] : fn.insns) indirect_calls += i.xfer == Xfer::CallIndirect;
        insns += fn.insns.size();
        EmitResult r;
        try {
            r = emit_function(fn, func_symbol(a), &image, demangle(f->name));
        } catch (const EmitError& e) {
            std::string why = e.what();
            for (char& ch : why)
                if (ch == '"' || ch == '\\') ch = '\'';
            stubbed[a] = why;
            bodies[a] = "// " + demangle(f->name) + "\n// NOT TRANSLATED: " +
                        why + "\nvoid " + func_symbol(a) +
                        "(scimitar::Context& c) {\n    (void)c;\n    scimitar::fatal(\"" +
                        func_symbol(a) + " was not translated: " + why + "\");\n}\n";
            continue;
        }
        bodies[a] = r.code;
        imports.insert(r.imports.begin(), r.imports.end());
        callees_of[a] = r.callees;
        for (uint32_t t : r.callees) work.push_back(t);
        // Virtual methods are reached only through vtables: when code refers to
        // a vtable (typically a constructor installing it), translate every
        // function the vtable points to.
        if (follow_vtables)
            for (uint32_t ref : fn.refs) {
                // Weak definitions (vtables of inline classes...) are reached
                // through a pointer slot bound to the image's own copy.
                std::vector<uint32_t> targets{ref};
                auto slot = image.pointer_slots().find(ref);
                if (slot != image.pointer_slots().end() && slot->second.internal)
                    targets.push_back(slot->second.internal);
                for (uint32_t a : targets) {
                    for (uint32_t t : image.vtable_functions(a))
                        if (!bodies.count(t) && !overridden.count(t)) {
                            work.push_back(t);
                            via_vtables.insert(t);
                        }
                    // A function whose address the code takes (a callback, a
                    // pthread_once routine, a thread entry) is called indirectly.
                    if (image.function_at(a) && !bodies.count(a) && !overridden.count(a)) {
                        work.push_back(a);
                        via_vtables.insert(a);
                    }
                }
            }
    }

    // Everything reachable from the roots through direct calls must have
    // translated; stubs are only acceptable behind a vtable.
    std::set<uint32_t> required;
    std::vector<uint32_t> todo = all ? std::vector<uint32_t>{} : root_addrs;
    while (!todo.empty()) {
        const uint32_t a = todo.back();
        todo.pop_back();
        if (!required.insert(a).second) continue;
        for (uint32_t t : callees_of[a]) todo.push_back(t);
    }
    for (const auto& [a, why] : stubbed)
        if (required.count(a)) {
            std::fprintf(stderr, "scimitar-recomp: %s (%s) is reachable by direct calls but "
                                 "could not be translated: %s\n", func_symbol(a).c_str(),
                         demangle(image.function_at(a)->name).c_str(), why.c_str());
            return 1;
        }

    // PE: every import gets a declaration (and a weak stub), and part 0 lists
    // them all for the loader, which fills the import address table: code also
    // calls imports through registers loaded from it.
    if (image.is_pe())
        for (const auto& [slot, imp] : image.stubs()) imports.insert(imp.name);

    // Output, in `parts` files of about equal size when splitting: each declares
    // the functions its code calls and registers its own functions.
    std::vector<std::vector<uint32_t>> groups(parts);
    if (image.is_pe()) {
        // PE: a function's part follows from its address alone, so discovering
        // or changing functions leaves the other parts as they were (and a
        // rebuild compiles only the changed parts).
        for (const auto& [a, b] : bodies) groups[(a >> 8) * 2654435761u % parts].push_back(a);
    } else {
        size_t total = 0, acc = 0;
        for (const auto& [a, b] : bodies) total += b.size();
        size_t g = 0;
        for (const auto& [a, b] : bodies) {
            if (g + 1 < parts && acc > total * (g + 1) / parts) g++;
            groups[g].push_back(a);
            acc += b.size();
        }
    }
    for (size_t g = 0; g < parts; g++) {
        std::set<uint32_t> declared;
        for (uint32_t a : groups[g]) {
            declared.insert(a);
            declared.insert(callees_of[a].begin(), callees_of[a].end());
        }
        std::string out;
        out += "// Generated by scimitar-recomp from " + path + ".\n";
        out += "// Contains translated game code: build output only, never commit. Do not edit.\n";
        out += "#include \"scimitar/runtime.h\"\n\n";
        out += "namespace scimitar::imports {\n";
        for (const auto& n : imports)
            out += "void " + import_symbol(n) + "(scimitar::Context& c);  // " + n + "\n";
        if (weak_imports) {
            // Imports without a shim yet fail loudly if called; a shim linked
            // in (strong definition) replaces the stub.
            for (const auto& n : imports)
                out += "[[gnu::weak]] void " + import_symbol(n) +
                       "(scimitar::Context& c) { scimitar::fatal(\"import " + n +
                       " is not implemented (called from %08x)\", c.mem->read<uint32_t>(c.esp)); }\n";
        }
        out += "}  // namespace scimitar::imports\n\nnamespace generated {\n";
        out += "using namespace scimitar::imports;\n\n";
        for (uint32_t a : declared)
            out += "void " + func_symbol(a) + "(scimitar::Context& c);" +
                   (overridden.count(a) ? "  // override, hand-written\n" : "\n");
        out += "\n";
        for (uint32_t a : groups[g]) out += bodies[a] + "\n";
        out += "}  // namespace generated\n\n";
        // Overridden functions forward to their hand-written replacement,
        // named after the symbol (override_symbol); the first part defines them.
        std::vector<uint32_t> entries = groups[g];
        if (g == 0 && !overridden.empty()) {
            out += "namespace scimitar::overrides {\n";
            for (uint32_t a : overridden)
                out += "void " + override_symbol(image.function_at(a)->name) + "(scimitar::Context& c);\n";
            out += "}  // namespace scimitar::overrides\n\nnamespace generated {\n";
            for (uint32_t a : overridden) {
                out += "// " + demangle(image.function_at(a)->name) + ": hand-written\n";
                out += "void " + func_symbol(a) + "(scimitar::Context& c) { scimitar::overrides::" +
                       override_symbol(image.function_at(a)->name) + "(c); }\n";
                entries.push_back(a);
            }
            out += "}  // namespace generated\n\n";
        }
        if (g == 0 && image.is_pe()) {
            out += "static const scimitar::ImportEntry kImports[] = {\n";
            for (const auto& n : imports)
                out += "    {\"" + n + "\", scimitar::imports::" + import_symbol(n) + "},\n";
            out += "};\nstatic scimitar::ImportRegistrar kImportRegistrar(kImports, sizeof kImports / sizeof *kImports);\n\n";
        }
        out += "static const scimitar::FuncEntry kFunctions[] = {\n";
        for (uint32_t a : entries) {
            char buf[64];
            std::snprintf(buf, sizeof buf, "    {0x%08xu, generated::", a);
            out += buf + func_symbol(a) + ", \"" + image.function_at(a)->name + "\"},\n";
        }
        if (entries.empty()) out += "    {0, nullptr, nullptr},\n";
        out += "};\nstatic scimitar::FuncRegistrar kRegistrar(kFunctions, " +
               std::string(entries.empty() ? "0" : "sizeof kFunctions / sizeof *kFunctions") +
               ");\n";
        std::string file = out_path;
        if (parts > 1) {
            const size_t dot = file.rfind(".cpp");
            file = (dot == std::string::npos ? file : file.substr(0, dot)) + "_" +
                   std::to_string(g) + ".cpp";
        }
        // An unchanged part keeps its file (and time stamp): a build after a
        // translator change recompiles only the parts whose code changed.
        {
            std::ifstream old(file, std::ios::binary);
            const std::string prev{std::istreambuf_iterator<char>(old), {}};
            if (prev == out) continue;
        }
        std::ofstream(file) << out;
    }

    std::fprintf(stderr, "translated %zu functions (%zu instructions, %d indirect call sites, "
                         "%zu reached through vtables or taken addresses); imports:",
                 bodies.size(), insns, indirect_calls, via_vtables.size());
    for (const auto& n : imports) std::fprintf(stderr, " %s", n.c_str());
    std::fprintf(stderr, "\n");
    if (!stubbed.empty()) {
        std::fprintf(stderr, "%zu functions left as stubs (fatal if called):\n", stubbed.size());
        for (const auto& [a, why] : stubbed)
            std::fprintf(stderr, "  %s %s: %s\n", func_symbol(a).c_str(),
                         demangle(image.function_at(a)->name).c_str(), why.c_str());
    }
    return 0;
}

int main(int argc, char** argv) {
    std::string bin, image, name, out;
    uint32_t addr = 0;
    std::vector<std::string> roots, overrides;
    bool follow_vtables = true, weak_imports = false;
    size_t parts = 1;
    for (int k = 1; k < argc; k++) {
        const std::string a = argv[k];
        if (a == "--no-vtables") {
            follow_vtables = false;
            continue;
        }
        if (a == "--weak-imports") {
            weak_imports = true;
            continue;
        }
        if (a == "--all") {
            roots = {"--all"};
            continue;
        }
        if (k + 1 >= argc) usage();
        const char* v = argv[++k];
        if (a == "--bin") bin = v;
        else if (a == "--addr") addr = (uint32_t)std::stoul(v, nullptr, 0);
        else if (a == "--name") name = v;
        else if (a == "--out") out = v;
        else if (a == "--image") image = v;
        else if (a == "--root") roots.push_back(v);
        else if (a == "--override") overrides.push_back(v);
        else if (a == "--parts") parts = std::max<size_t>(1, std::stoul(v));
        else if (a == "--roots-file") {
            std::ifstream rf(v);
            if (!rf) {
                std::fprintf(stderr, "cannot read %s\n", v);
                return 1;
            }
            for (std::string l; std::getline(rf, l);)
                if (!l.empty() && l[0] != '#') roots.push_back(l.substr(0, l.find_first_of(" \t")));
        }
        else usage();
    }
    if (out.empty()) usage();
    if (!bin.empty() && addr && !name.empty()) return fixture_mode(bin, addr, name, out);
    if (!image.empty() && !roots.empty()) return image_mode(image, roots, overrides, follow_vtables, weak_imports, parts, out);
    usage();
}
